@dataclass(frozen=True)
class Hint:
    """Один структурный образец."""

    name: str
    shape: str
    guess: str
    method: str
    example: str
    status: str
    note: str
    pattern: re.Pattern[str]

    def __str__(self) -> str:
        return f"{self.shape} → {self.guess} ({self.status}); {self.method}"

    def markdown(self) -> str:
        lines = [
            f"**{self.shape}** → предположительно **{self.guess}**",
            "",
            f"* образец: `{self.example}`",
            f"* чем доказывать: {self.method}",
            f"* надёжность: {self.status}",
        ]
        if self.note:
            lines.append(f"* оговорка: {self.note}")
        return "\n".join(lines)


def _hint(name, shape, guess, method, example, status, note, pattern) -> Hint:
    return Hint(name, shape, guess, method, example, status, note, re.compile(pattern, re.I))


