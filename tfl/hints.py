def match(text: str, limit: int = 4) -> list[Hint]:
    """Образцы, подходящие к тексту условия, по убыванию числа улик.

    Это **генератор гипотез**, а не классификатор: несколько образцов
    сразу — норма, и каждый проверяется своим оракулом.
    """
    scored: list[tuple[int, int, Hint]] = []
    for index, hint in enumerate(HINTS):
        found = len(hint.pattern.findall(text))
        if found:
            scored.append((found, -index, hint))
    scored.sort(reverse=True)
    return [hint for _, _, hint in scored[:limit]]
