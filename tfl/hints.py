"""База структурных образцов: «язык такого вида → гипотеза → чем доказывать».

`tfl/intake.py` определяет **класс задачи** — какой рецепт открывать.
Он ничего не говорит о том, каким окажется ответ и с какой стороны
за него браться. Эта база закрывает вторую половину: по форме условия
она подсказывает **вероятный вердикт и метод**.

Откуда взялась. Идея — из чужого агента по ТФЯ (`ark2016/TFL-automatisation`,
разбор в `reports/vendor-repos/NOTES.md`, §3.4): там 20 записей вида
«структурный образец → предполагаемый вердикт → каким методом доказывать».
Взята **идея и содержание**, не код; список переписан под наши оракулы,
дополнен приёмами курса, которых у них нет, и — главное — размечен
по надёжности.

Разметка обязательна, потому что часть исходных записей **неверна как
записана**, и брать их за факты нельзя:

* «реверс DCFL — не DCFL». Реверс регулярного языка регулярен, а всякий
  регулярный язык детерминированно контекстно-свободен. Контрпример
  предъявляется исполнением (см. `tests/test_hints.py`).
* «дополнение известного языка — DCFL» с примером `¬{aⁿbⁿcⁿ}`. DCFL
  замкнут относительно дополнения; будь дополнение детерминированным,
  детерминированным был бы и сам язык, а `{aⁿbⁿcⁿ}` даже не КС.

Ещё две записи не ошибочны, но **слабее истины**: `{aⁿbⁿcⁿ}` и
конфликтующие сравнения длин там объявлены «не DCFL», тогда как они
не контекстно-свободны вовсе, и доказывать надо это.

Отсюда поле `status`:

| Значение | Что означает |
|---|---|
| `THEOREM` | следует из теоремы курса; вердикт надёжен, остаётся его оформить |
| `HEURISTIC` | верно для типичных условий, но не теорема — оракул обязателен |
| `WEAK` | вердикт верен, но слабее достижимого: доказывать надо большее |
| `WRONG` | как записано — неверно; хранится с контрпримером, чтобы не повторять |

**База не выносит вердикт.** Она называет гипотезу и оракул, которым
её проверяют. Правило проекта прежнее: утверждение, не прогнанное через
оракул, идёт в отчёт с пометкой `[НЕ ПРОВЕРЕНО]`.
"""

